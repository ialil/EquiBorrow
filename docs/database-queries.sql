CREATE TABLE "Equipment" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "Identifier" character varying(50) NOT NULL,
    "IdentifierKey" text GENERATED ALWAYS AS (lower(btrim("Identifier"))) STORED NOT NULL,
    "Name" character varying(200) NOT NULL,
    "Description" character varying(500),
    "IsAvailable" boolean NOT NULL,
    CONSTRAINT "PK_Equipment" PRIMARY KEY ("Id"),
    CONSTRAINT "CK_Equipment_Description_NotBlank" CHECK ("Description" IS NULL OR btrim("Description") <> ''),
    CONSTRAINT "CK_Equipment_Identifier_NotBlank" CHECK (btrim("Identifier") <> ''),
    CONSTRAINT "CK_Equipment_Name_NotBlank" CHECK (btrim("Name") <> '')
);


CREATE TABLE "Students" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "StudentNumber" character varying(50) NOT NULL,
    "StudentNumberKey" text GENERATED ALWAYS AS (lower(btrim("StudentNumber"))) STORED NOT NULL,
    "Name" character varying(200) NOT NULL,
    "Contact" character varying(200),
    "IsActive" boolean NOT NULL,
    CONSTRAINT "PK_Students" PRIMARY KEY ("Id"),
    CONSTRAINT "CK_Students_Contact_NotBlank" CHECK ("Contact" IS NULL OR btrim("Contact") <> ''),
    CONSTRAINT "CK_Students_Name_NotBlank" CHECK (btrim("Name") <> ''),
    CONSTRAINT "CK_Students_StudentNumber_NotBlank" CHECK (btrim("StudentNumber") <> '')
);


CREATE TABLE "Borrowings" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "StudentId" integer NOT NULL,
    "EquipmentId" integer NOT NULL,
    "BorrowDate" date NOT NULL,
    "ExpectedReturnDate" date NOT NULL,
    "Status" integer NOT NULL,
    "ReturnDate" date,
    CONSTRAINT "PK_Borrowings" PRIMARY KEY ("Id"),
    CONSTRAINT "CK_Borrowings_ExpectedAfterBorrow" CHECK ("ExpectedReturnDate" > "BorrowDate"),
    CONSTRAINT "CK_Borrowings_ReturnState" CHECK (("Status" = 0 AND "ReturnDate" IS NULL) OR ("Status" = 1 AND "ReturnDate" IS NOT NULL AND "ReturnDate" >= "BorrowDate")),
    CONSTRAINT "FK_Borrowings_Equipment_EquipmentId" FOREIGN KEY ("EquipmentId") REFERENCES "Equipment" ("Id") ON DELETE RESTRICT,
    CONSTRAINT "FK_Borrowings_Students_StudentId" FOREIGN KEY ("StudentId") REFERENCES "Students" ("Id") ON DELETE RESTRICT
);


CREATE INDEX "IX_Borrowings_Equipment_BorrowDate" ON "Borrowings" ("EquipmentId", "BorrowDate");


CREATE INDEX "IX_Borrowings_Student_Status" ON "Borrowings" ("StudentId", "Status");


CREATE UNIQUE INDEX "UX_Borrowings_OneActivePerEquipment" ON "Borrowings" ("EquipmentId") WHERE "Status" = 0;


CREATE UNIQUE INDEX "UX_Equipment_IdentifierKey" ON "Equipment" ("IdentifierKey");


CREATE UNIQUE INDEX "UX_Students_StudentNumberKey" ON "Students" ("StudentNumberKey");


